// Generates src/commands/registry.ts, the list of CLI commands that src/cli.ts adds to the
// program, from the *.command.ts files in src/commands/.
//
// Each command file must default-export a factory that returns a commander `Command`.
// Placeholder files with no code (comments and `export {}` only) are skipped. A file that has
// code but no default export is an error, so a command is never silently left out.
//
// The registry uses static imports, so tsc, tsx, Jest, and `deno compile` all see every
// command. It is committed; the generator runs before dev, build, test, and compile, and CI
// runs it with --check.
//
// Usage: node scripts/generate-commands.mjs [--check]
//   --check  exit 1 if registry.ts is missing or out of date, without writing it
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export const REGISTRY_FILE = 'registry.ts';

const commandFilePattern = /^([a-z][a-z0-9]*(?:-[a-z0-9]+)*)\.command\.ts$/;

const stripComments = (source) => source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/.*$/gm, '');

export const hasCode = (source) => stripComments(source)
    .replace(/\bexport\s*\{\s*\}\s*;?/g, '')
    .trim() !== '';

export const hasDefaultExport = (source) => /^\s*export\s+default\b/m.test(stripComments(source));

/** `env-sync.command.ts` -> `envSyncCommand` */
export const toIdentifier = (name) =>
    `${name.replace(/-([a-z0-9])/g, (_match, char) => char.toUpperCase())}Command`;

/**
 * Lists the command modules in `dir`, sorted by filename.
 *
 * @returns `{ file, identifier }` for each file to register.
 * @throws When a `*.command.ts` filename isn't kebab-case, or a file has code but no default export.
 */
export const findCommands = (dir) => {
    const errors = [];
    const commands = [];

    for (const file of readdirSync(dir).filter((f) => f.endsWith('.command.ts')).sort()) {
        const match = commandFilePattern.exec(file);
        if (!match) {
            errors.push(`${file}: command filenames must be kebab-case, e.g. env-sync.command.ts`);
            continue;
        }

        const source = readFileSync(path.join(dir, file), 'utf8');
        if (!hasCode(source)) continue;

        if (!hasDefaultExport(source)) {
            errors.push(`${file}: must default-export a function that returns a commander Command`);
            continue;
        }

        commands.push({ file, identifier: toIdentifier(match[1]) });
    }

    if (errors.length > 0) {
        throw new Error(`Invalid command files in ${dir}:\n${errors.map((e) => `  - ${e}`).join('\n')}`);
    }

    return commands;
};

/** Renders registry.ts for the given commands. */
export const renderRegistry = (commands) => {
    const imports = commands
        .map(({ file, identifier }) => `import ${identifier} from './${file.replace(/\.ts$/, '.js')}';\n`)
        .join('');
    const entries = commands.map(({ identifier }) => `    ${identifier},\n`).join('');

    return `// Generated by scripts/generate-commands.mjs. Do not edit by hand; run
// \`pnpm generate:commands\` after adding, renaming, or removing a command.
import type { Command } from "commander";
${imports}
/** Factories for every command in \`src/commands/\`, in filename order. */
export const commandFactories: ReadonlyArray<() => Command> = [
${entries}];
`;
};

/**
 * Writes (or with `check`, verifies) the registry for `dir`.
 *
 * @returns `true` when the registry on disk is current (or was written).
 */
export const generate = (dir, { check = false } = {}) => {
    const registryPath = path.join(dir, REGISTRY_FILE);
    const expected = renderRegistry(findCommands(dir));
    const current = existsSync(registryPath) ? readFileSync(registryPath, 'utf8') : null;

    if (check) return current === expected;
    if (current !== expected) writeFileSync(registryPath, expected);
    return true;
};

const isMain = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isMain) {
    const dir = path.resolve(import.meta.dirname, '../src/commands');
    const check = process.argv.includes('--check');

    try {
        if (!generate(dir, { check })) {
            console.error(`${path.relative(process.cwd(), path.join(dir, REGISTRY_FILE))} is out of date. Run \`pnpm generate:commands\` and commit the result.`);
            process.exit(1);
        }
    } catch (error) {
        console.error(error.message);
        process.exit(1);
    }
}
