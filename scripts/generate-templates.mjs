// Generates src/config/project-template.ts, the files `dev-setup bootstrap` creates, from the
// project template in templates/node-ts/.
//
// The template is kept as real files so it's easy to edit, but `deno compile` only bundles code
// the program imports, so files read from disk at runtime would be missing from the standalone
// binaries. Embedding them in a generated module keeps them in every build.
//
// Files are stored under their output paths, with two exceptions: `_gitignore` becomes
// `.gitignore` (stored without the dot so it doesn't apply to this repo), and `\r\n` line endings
// are normalized to `\n` so the output doesn't depend on Git's line-ending settings.
//
// The module is committed; the generator runs before dev, build, test, and compile, and CI runs
// it with --check.
//
// Usage: node scripts/generate-templates.mjs [--check]
//   --check  exit 1 if project-template.ts is missing or out of date, without writing it
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export const TEMPLATE_DIR = 'templates/node-ts';
export const TEMPLATE_MODULE = 'src/config/project-template.ts';

/** `_gitignore` -> `.gitignore`, in any directory. */
export const toOutputPath = (relativePath) => relativePath
    .split('/')
    .map((part) => (part === '_gitignore' ? '.gitignore' : part))
    .join('/');

/**
 * Lists every file under `dir`, recursively.
 *
 * @returns Paths relative to `dir`, using `/` separators.
 */
export const listFiles = (dir, prefix = '') => readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
        const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
        return entry.isDirectory()
            ? listFiles(path.join(dir, entry.name), relativePath)
            : [relativePath];
    });

/**
 * Reads the template in `dir`.
 *
 * @returns `{ path, contents }` for each file, sorted by output path.
 * @throws When the template has no files, or two files map to the same output path.
 */
export const readTemplate = (dir) => {
    const files = listFiles(dir)
        .map((file) => ({
            path: toOutputPath(file),
            contents: readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n'),
        }))
        .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));

    if (files.length === 0) throw new Error(`${dir} has no template files.`);

    const duplicates = files.filter((file, i) => i > 0 && files[i - 1].path === file.path);
    if (duplicates.length > 0) {
        throw new Error(`${dir} has more than one file for: ${duplicates.map((file) => file.path).join(', ')}`);
    }

    return files;
};

/** Renders project-template.ts for the given files. */
export const renderTemplateModule = (files) => {
    const entries = files
        .map(({ path: filePath, contents }) =>
            `    {\n        path: ${JSON.stringify(filePath)},\n        contents: ${JSON.stringify(contents)},\n    },\n`)
        .join('');

    return `// Generated by scripts/generate-templates.mjs from ${TEMPLATE_DIR}/. Do not edit by hand; edit
// the template files and run \`pnpm generate:templates\`.

/** A file in the project template: its path relative to the project root, and its contents. */
export interface TemplateFile {
    /** Path relative to the new project's root, using \`/\` separators. */
    path: string;
    /** File contents. \`{{name}}\` is replaced with the project name. */
    contents: string;
}

/** Files \`dev-setup bootstrap\` creates, sorted by path. */
export const PROJECT_TEMPLATE: ReadonlyArray<TemplateFile> = [
${entries}];
`;
};

/**
 * Writes (or with `check`, verifies) the template module.
 *
 * @returns `true` when the module on disk is current (or was written).
 */
export const generate = (templateDir, modulePath, { check = false } = {}) => {
    const expected = renderTemplateModule(readTemplate(templateDir));
    const current = existsSync(modulePath) ? readFileSync(modulePath, 'utf8') : null;

    if (check) return current === expected;
    if (current !== expected) writeFileSync(modulePath, expected);
    return true;
};

const isMain = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isMain) {
    const root = path.resolve(import.meta.dirname, '..');
    const modulePath = path.join(root, TEMPLATE_MODULE);
    const check = process.argv.includes('--check');

    try {
        if (!generate(path.join(root, TEMPLATE_DIR), modulePath, { check })) {
            console.error(`${TEMPLATE_MODULE} is out of date. Run \`pnpm generate:templates\` and commit the result.`);
            process.exit(1);
        }
    } catch (error) {
        console.error(error.message);
        process.exit(1);
    }
}
